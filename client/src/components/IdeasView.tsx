"use strict";

import type { IdeasResponse, PlanBundle } from '@shared/types';

interface Props {
  ideas: IdeasResponse | null;
  plan: PlanBundle;
}

const formatINR = (n: number): string => `₹${Math.round(n).toLocaleString('en-IN')}`;

const CATEGORY_LABEL: Record<string, string> = {
  decor: 'Decor',
  menu: 'Menu',
  activities: 'Activities',
  entertainment: 'Entertainment',
};

const IdeasView = ({ ideas, plan }: Props) => {
  if (!ideas) {
    return (
      <div className="card">
        <h2>Ideas</h2>
        <p style={{ color: 'var(--muted)' }}>Ideas load with the plan.</p>
      </div>
    );
  }

  return (
    <div className="card">
      <h2>Personalized ideas</h2>
      {ideas.source === 'fallback' && (
        <p className="chip chip-warn" role="status" style={{ display: 'inline-block', margin: '0.5rem 0 1rem' }}>
          Using offline suggestions — set server AI credentials for live AI ideas
        </p>
      )}
      {ideas.source === 'ai' && (
        <p className="chip chip-success" style={{ display: 'inline-block', margin: '0.5rem 0 1rem' }}>
          Generated by AI within your budget caps
        </p>
      )}

      <p style={{ fontStyle: 'italic', margin: '0.5rem 0 1.5rem' }}>{ideas.ideas.themeConcept}</p>

      <div className="stat-grid" style={{ gridTemplateColumns: 'repeat(auto-fit, minmax(240px, 1fr))' }}>
        {ideas.ideas.items.map((item, i) => (
          <div className="stat-card" key={i}>
            <div className="stat-label">{CATEGORY_LABEL[item.category] ?? item.category}</div>
            <h3 style={{ margin: '0.25rem 0' }}>{item.title}</h3>
            <p style={{ fontSize: '0.88rem', color: 'var(--muted)' }}>{item.description}</p>
            <div style={{ marginTop: '0.5rem', display: 'flex', gap: '0.5rem', alignItems: 'center', flexWrap: 'wrap' }}>
              <span className="chip chip-warn">{formatINR(item.estimatedCost)}</span>
              {item.fitsBudget ? (
                <span className="chip chip-success">Fits budget</span>
              ) : (
                <span className="chip chip-alert">Over by {formatINR(item.overBy ?? 0)}</span>
              )}
            </div>
          </div>
        ))}
      </div>

      <p style={{ fontSize: '0.8rem', color: 'var(--muted)', marginTop: '1rem' }}>
        Idea costs are capped by your {plan.setup.eventType} budget lines — the AI never invents totals.
      </p>
    </div>
  );
};

export default IdeasView;
